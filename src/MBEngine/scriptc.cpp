// keeps the column count for error messages
// 0x100334f0 ?UpdateCharacterCount@@YAXXZ
inline void UpdateCharacterCount()
{
    for (int i = 0; yytext[i] != '\0'; i++)
        if (yytext[i] == '\n')
            gColumnCnt = 0;
        else if (yytext[i] == '\t')
            gColumnCnt += 8 - (gColumnCnt % 8);
        else
            gColumnCnt++;
}

