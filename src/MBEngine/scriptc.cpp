// 0x1002f5c0 ?HardExit@@YAXPBD@Z
void __cdecl HardExit(const char *str)
{
    MBDebugStr("\nError: %s\n", str);
    gBytesWritten = -1;
}

// 0x1002f5e0 ?SafeTell@@YAKPAVIMBStream@@@Z
unsigned long __cdecl SafeTell(IMBStream *inFile)
{
    unsigned long pos = inFile->GetPosition();
    if (pos == (unsigned long)-1)
    {
        HardExit("Error getting output file position!");
        pos = 0;
    }
    return pos;
}

// 0x1002f600 ?SafeSeek@@YAXPAVIMBStream@@JW4IMBStreamSeekValues@@@Z
void __cdecl SafeSeek(IMBStream *inFile, long offset, IMBStreamSeekValues origin)
{
    if (!inFile->Seek(offset, origin))
    {
        HardExit("Error setting output file position!");
    }
}

// the writers of the code block; Write(short) is emitted out of line where it is not inlined
// TODO 0x10035b60 ?Write@@YAXF@Z: emitted out of line only where yyparse calls it
inline void Write(short code)
{
    if (gBytesWritten != -1) {
        if (!gOutStream->Write(&code, sizeof(short)))
            HardExit("Error writing to output file!");
    }
}

inline void Write(long code)
{
    if (gBytesWritten != -1) {
        if (!gOutStream->Write(&code, sizeof(long)))
            HardExit("Error writing to output file!");
    }
}

inline void Write(float code)
{
    if (gBytesWritten != -1) {
        if (!gOutStream->Write(&code, sizeof(float)))
            HardExit("Error writing to output file!");
    }
}

