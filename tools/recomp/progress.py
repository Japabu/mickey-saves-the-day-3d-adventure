"""Render the progress block of README.md.

Measures, per module, the code of the game functions (all functions minus the
statically linked library code listed in src/lib/<bin>.txt and C++ EH funclets) in
bytes, in three parts: functions the source claims (`// 0x<va> <symbol>`, identical
bytes, checked by tools/msvc/check.sh), functions written but not identical yet
(`// TODO 0x<va>` followed by a body) and the rest. Function boundaries come from
tools/recomp/match.py, the compiler from the PE linker version.

  progress.py                      print the block
  progress.py --update-readme      replace it in README.md between the markers, computed
                                   from the committed state (HEAD) in a temporary checkout
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
import match  # noqa: E402
import pe  # noqa: E402
import sources  # noqa: E402

BIN = os.path.join(ROOT, 'orig', 'binaries')
START, END = '<!-- progress:start -->', '<!-- progress:end -->'
MODULES = ['Steamboat.exe', 'SteamboatApp.dll', 'MBEngine.dll', 'MBCom.dll', 'mbruntime.dll',
           'RuntimeLib.dll', 'MfActorLib.dll', 'MfPoLibrary.dll', 'MfImageLib.dll',
           'PiccoloRT.dll', 'PiccoloComp.dll', 'PiccoloConsole.dll', 'mflinalg.dll',
           'mfutil.dll', 'zlib.dll']


def all_modules():
    plugins = sorted('plugins/' + f for f in os.listdir(os.path.join(BIN, 'plugins'))
                     if f.lower().endswith('.dll'))
    return MODULES + plugins


class Module:
    def __init__(self, name):
        self.name = name
        p = pe.PE(os.path.join(BIN, name))
        self.compiler = {5: 'VC5', 6: 'VC6'}.get(p.data[p.opt_off + 2], '?')
        self.game = self.matched = self.equivalent = self.reviewed = self.written = 0      # bytes
        self.funcs = self.funcs_matched = 0


def count(mods):
    done, written = {}, {}
    for b, va in sources.claims():
        done.setdefault(b, set()).add(va)
    equivalent, reviewed = {}, {}
    for (b, va) in sources.equivs(kind='proven'):
        equivalent.setdefault(b, set()).add(va)
    for (b, va) in sources.equivs(kind='reviewed'):
        reviewed.setdefault(b, set()).add(va)
    for (b, va), (_, _, body) in sources.todos().items():
        if body:
            written.setdefault(b, set()).add(va)
    for m in mods:
        img = match.Image.get(m.name)
        libf = os.path.join(ROOT, 'src', 'lib', m.name.replace('/', '_') + '.txt')
        lib = set()
        if os.path.isfile(libf):
            lib = {int(l.split()[0], 16) for l in open(libf) if l.strip() and not l.startswith('#')}
        game = [va for va in img.funcs if va not in lib and va not in img.eh]
        keys = (m.name.split('/')[-1].lower(), m.name.lower())
        mine = set().union(*(done.get(k, set()) for k in keys))
        same = set().union(*(equivalent.get(k, set()) for k in keys)) - mine
        judged = set().union(*(reviewed.get(k, set()) for k in keys)) - mine - same
        todo = set().union(*(written.get(k, set()) for k in keys)) - mine - same - judged
        for va in game:
            size = img.funcs[va][0] - va
            m.game += size
            m.funcs += 1
            if va in mine:
                m.matched += size
                m.funcs_matched += 1
            elif va in same:
                m.equivalent += size
            elif va in judged:
                m.reviewed += size
            elif va in todo:
                m.written += size


def bar(frac, width, decimals=0):
    n = round(frac * width)
    if frac < 1:
        n = min(n, width - 1)
    if frac > 0:
        n = max(n, 1)
    p = frac * 100
    if decimals == 0 and 0 < frac < 1:
        p = min(max(round(p), 1), 99)
    return '`' + '█' * n + '░' * (width - n) + f' {p:>{3 if not decimals else 0}.{decimals}f}%`'


def kib(n):
    return f'{n / 1024:,.1f} KiB' if n < 10 * 1024 else f'{n / 1024:,.0f} KiB'


def pct(part, whole):
    return f'{100 * part / whole:.1f}%' if whole else '—'


def render():
    mods = [Module(n) for n in all_modules()]
    count(mods)
    game = sum(m.game for m in mods)
    matched = sum(m.matched for m in mods)
    written = sum(m.written for m in mods)
    equivalent = sum(m.equivalent for m in mods)
    reviewed = sum(m.reviewed for m in mods)
    funcs = sum(m.funcs for m in mods)
    funcs_matched = sum(m.funcs_matched for m in mods)
    out = [START,
           '<!-- generated by tools/recomp/progress.py --update-readme; do not edit by hand -->',
           '',
           f'{bar(matched / game, 20, 2)} of game code  ',
           f'{kib(matched)} of {kib(game)} of game code ({funcs_matched:,} of {funcs:,} functions) '
           'compiles to identical bytes (checked by `tools/msvc/check.sh`). '
           f'{kib(equivalent)} ({pct(equivalent, game)}) more is proven the same logic up to '
           'register and stack-slot renaming (`// EQUIV ...: proven`, re-proven by `check.sh`), '
           f'{kib(reviewed)} ({pct(reviewed, game)}) is reviewed as the same logic by comparing '
           'both instruction streams (`// EQUIV ...: reviewed`), and '
           f'{kib(written)} ({pct(written, game)}) is written as source but neither yet '
           '(`// TODO`). Statically linked library code and EH funclets are not counted.',
           '',
           '| Module | Compiler | Game code | Identical | Proven same | Reviewed same | Written, differs | Not written | |',
           '|---|---|--:|--:|--:|--:|--:|--:|---|']
    for m in mods:
        row = bar(m.matched / m.game, 10) if m.game else '—'
        rest = m.game - m.matched - m.equivalent - m.reviewed - m.written
        out.append(f'| `{m.name}` | {m.compiler} | {kib(m.game)} | {pct(m.matched, m.game)} '
                   f'| {pct(m.equivalent, m.game)} | {pct(m.reviewed, m.game)} | {pct(m.written, m.game)} '
                   f'| {pct(rest, m.game)} | {row} |')
    out += ['', END]
    return '\n'.join(out) + '\n'


def update_readme(path, block):
    with open(path, encoding='utf-8') as f:
        text = f.read()
    a, b = text.find(START), text.find(END)
    if a < 0 or b < a:
        sys.exit(f'{path}: markers {START} / {END} not found')
    new = text[:a] + block.rstrip('\n') + text[b + len(END):]
    if new != text:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(new)


def committed_block():
    """The block for the committed state (HEAD), not the working tree, which may hold
    other people's unfinished edits: computed in a temporary checkout of HEAD."""
    import subprocess
    import tempfile
    tmp = tempfile.mkdtemp(prefix='progress.', dir=os.path.join(ROOT, 'out'))
    try:
        subprocess.run(['git', '-C', ROOT, 'worktree', 'add', '-q', '--detach', tmp, 'HEAD'], check=True)
        os.makedirs(os.path.join(tmp, 'out'), exist_ok=True)
        os.symlink(os.path.join(ROOT, 'out', 'cache'), os.path.join(tmp, 'out', 'cache'))
        # the imported game binaries are not committed
        os.symlink(os.path.join(ROOT, 'orig'), os.path.join(tmp, 'orig'))
        res = subprocess.run([sys.executable, os.path.join(tmp, 'tools', 'recomp', 'progress.py')],
                             check=True, capture_output=True, text=True)
        return res.stdout
    finally:
        subprocess.run(['git', '-C', ROOT, 'worktree', 'remove', '--force', tmp], capture_output=True)
        subprocess.run(['git', '-C', ROOT, 'worktree', 'prune'], capture_output=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--update-readme', action='store_true',
                    help='rewrite the block between the progress markers in README.md')
    a = ap.parse_args()
    block = committed_block() if a.update_readme else render()
    if a.update_readme:
        update_readme(os.path.join(ROOT, 'README.md'), block)
    else:
        sys.stdout.write(block)


if __name__ == '__main__':
    main()
